/**
 * Тёплые напутствия по уровню результата.
 * Не врачебные — мотивирующий тон «Женского мира».
 */

export const BLESSING_FINAL =
  'Помните: каждая история уникальна. Нет «правильного» уровня желания — есть ваш путь и ваш темп. Берегите себя. 💛';

export const BLESSINGS = {
  low:
    'Снижение желания — это не приговор. Так бывает: усталость, стресс, цикл, перемены в теле и отношениях. Вы уже сделали важный шаг — посмотрели на себя с заботой. Можно мягко прислушаться к себе и, если захочется, спокойно разобрать это со специалистом — без спешки и оценок.',
  mid:
    'У вас есть ресурс — и тепло, и пространство для мягкой настройки под себя. Не обязательно гнаться за «должно быть сильнее»: ваш темп уже достаточно хороший. Замечайте, что работает, и бережно подсвечивайте то, что хочется развить.',
  high:
    'Прекрасный показатель: желание в целом живое и сохранённое. Можно просто радоваться тому, что уже есть, и направлять энергию так, как откликается вам. Бережность к себе усиливает близость.',
  very_high:
    'Высокая сексуальная энергия — живой дар. Важно направлять её бережно: так, как комфортно телу и сердцу. Ваш ритм — ваш, и это сила.',
};

/**
 * @param {string} [level]
 * @returns {'low'|'mid'|'high'|'very_high'}
 */
export function blessingBand(level) {
  const s = String(level || '').toLowerCase();
  if (/очень\s*высок|very\s*high/.test(s)) return 'very_high';
  if (/низк|low/.test(s)) return 'low';
  if (/средн|норм|умерен|mid/.test(s)) return 'mid';
  if (/высок|high/.test(s)) return 'high';
  return 'mid';
}

/** @param {string} [level] */
export function blessingForLevel(level) {
  const band = blessingBand(level);
  return {
    band,
    text: BLESSINGS[band],
    final: BLESSING_FINAL,
  };
}
